const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../js/content.js'), 'utf8'), context);
const days = context.window.ADVENT_CONTENT;
assert.equal(days.length, 25, 'devono esserci esattamente 25 contenuti');
assert.match(days[7].title, /Maria|Immacolata/i, 'l’8 dicembre deve avere il contenuto mariano');
assert.match(days[23].category, /vigilia/i, 'il 24 dicembre deve essere la Vigilia');
assert.match(days[24].title, /Verbo|Natale/i, 'il 25 dicembre deve celebrare la Natività');
assert.ok(days.every(day => day.title && day.body && day.reference), 'ogni contenuto deve avere titolo, testo e riferimento');
console.log('✓ 25 contenuti presenti e sequenza 8/24/25 coerente');
